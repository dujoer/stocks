def rows_from_csv(text):
    out = []
    for r in csv.reader(io.StringIO(text)):
        if len(r) < 14:
            continue
        out.append({
            "code": r[0], "name": r[1],
            "changePct": float(r[2]), "turnover": float(r[3]),
            "turnoverRate": float(r[4]), "upCount": r[5],
            "mainInflow": float(r[6]), "mainOutflow": float(r[7]),
            "mainNetInflow": float(r[8]),
            "mainNetInflow5d": float(r[9]), "mainNetInflow20d": float(r[10]),
            "leader": {"code": r[11], "name": r[12], "changePct": float(r[13])},
        })
    return out


def dump(rows, kind, path):
    payload = {"ok": True, "data": {"kind": kind, "type": "changepct",
                                    "order": "desc", "rows": rows}}
    json.dump(payload, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"[ok] {path}  kind={kind} rows={len(rows)}")


def main():
    irows = rows_from_csv(INDUSTRY_CSV)
    dump(irows, "industry", os.path.join(Q, f"sector_industry_{COMPACT}.json"))

    src = json.load(open(SRC_CONCEPT, encoding="utf-8"))
    crows = src["data"]["rows"]
    assert src["data"]["kind"] == "concept", src["data"]["kind"]
    dump(crows, "concept", os.path.join(Q, f"sector_concept_{COMPACT}.json"))
    print(f"[done] {DATE} 行业 {len(irows)} / 概念 {len(crows)}")


if __name__ == "__main__":
    main()
